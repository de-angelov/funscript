import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { renderCliReference } from "../dist/cli/commands.js";
import { DOC_CATALOG } from "../dist/lsp/docs.js";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const pkg = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));

const findFunScriptFiles = async (directory) => {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const file = join(directory, entry.name);
    if (entry.isDirectory()) return findFunScriptFiles(file);
    return entry.isFile() && (file.endsWith(".fun") || file.endsWith(".funx")) ? [file] : [];
  }));
  return nested.flat();
};

const renderLanguageReference = () => {
  const entries = Object.values(DOC_CATALOG).sort((a, b) => a.name.localeCompare(b.name));
  return `<!-- Generated by scripts/generate-reference-docs.mjs from src/lsp/docs.ts. Do not edit directly. -=>

# Language reference

This catalogue is the same metadata used by Language Server hover help. For runnable
programs, use the [validated example inventory](examples.md).

${entries.map((item) => `## \`${item.name}\`

${item.summary}

\`\`\`funscript
${item.signature}
\`\`\`

${item.description}

${item.seeAlso?.length ? `\nSee also: ${item.seeAlso.map((name) => `\`${name}\``).join(", ")}.` : ""}`).join("\n\n")}
`;
};

const exampleFiles = (await Promise.all(["examples", "programs"].map((directory) => findFunScriptFiles(resolve(root, directory)))))
  .flat()
  .filter((file) => !relative(root, file).startsWith("examples/fixtures/"))
  .sort();
const exampleRows = exampleFiles.map((file) => {
  const path = relative(root, file).replaceAll("\\", "/");
  return `| [\`${path}\`](../${path}) | \`${path.endsWith(".funx") ? "FunScript JSX" : "FunScript"}\` |`;
}).join("\n");

const readmeFacts = `<!-- GENERATED: project-facts -=>
## Generated project facts

- Package: \`${pkg.name}\` \`${pkg.version}\`
- Runtime: Effect \`${pkg.dependencies.effect}\`
- Source extensions: \`.fun\`, \`.funx\`
- Runnable checked examples: ${exampleFiles.length}

The exact command surface is generated from the implementation in the [CLI reference](docs/reference/cli.md). The language catalogue used by editor hover help is generated in the [language reference](docs/reference/language.md).
<!-- /GENERATED: project-facts -=>`;

const readmeExamples = `<!-- GENERATED: example-inventory -=>
${exampleRows.replaceAll("../", "")}
<!-- /GENERATED: example-inventory -=>`;

if (!check) await mkdir(resolve(root, "docs/reference"), { recursive: true });

const apiReference = `<!-- Generated by scripts/generate-reference-docs.mjs. Do not edit directly. -=>

# Package entry points

Package: \`${pkg.name}\` ${pkg.version}.

| Import | Implementation |
| --- | --- |
${Object.entries(pkg.exports).map(([entrypoint, implementation]) => `| \`${pkg.name}${entrypoint === "." ? "" : entrypoint.slice(1)}\` | \`${implementation}\` |`).join("\n")}
`;

const outputs = new Map([
  [resolve(root, "docs/reference/cli.md"), renderCliReference(pkg.version)],
  [resolve(root, "docs/reference/api.md"), apiReference],
  [resolve(root, "docs/reference/language.md"), renderLanguageReference()],
  [resolve(root, "docs/reference/examples.md"), `<!-- Generated by scripts/generate-reference-docs.mjs. Do not edit directly. -=>\n\n# Example inventory\n\nEvery entry below is compiled by \`npm run test:examples\`.\n\n| File | Kind |\n| --- | --- |\n${exampleRows}\n`],
]);

const readme = await readFile(resolve(root, "README.md"), "utf8");
const generatedReadme = readme
  .replace(/<!-- GENERATED: project-facts -=>[\s\S]*?<!-- \/GENERATED: project-facts -=>/, readmeFacts)
  .replace(/<!-- GENERATED: example-inventory -=>[\s\S]*?<!-- \/GENERATED: example-inventory -=>/, readmeExamples);
if (generatedReadme === readme && !readme.includes("<!-- GENERATED: project-facts -=>")) {
  throw new Error("README.md is missing generated documentation markers");
}
outputs.set(resolve(root, "README.md"), generatedReadme);

let stale = false;
for (const [file, content] of outputs) {
  let existing = "";
  try {
    existing = await readFile(file, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (existing === content) continue;
  stale = true;
  if (!check) await writeFile(file, content);
  console.log(`${check ? "Outdated" : "Generated"}: ${file}`);
}

if (check && stale) {
  console.error("Generated references are stale. Run: npm run docs:generate");
  process.exitCode = 1;
}
