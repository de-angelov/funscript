import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

export async function loadLanguageContracts(root) {
  const directory = resolve(root, "tests/fixtures/language-contracts");
  const catalog = JSON.parse(await readFile(resolve(directory, "catalog.json"), "utf8"));
  const contracts = await Promise.all(catalog.contracts.map(async (contract) => ({
    ...contract,
    source: await readFile(resolve(directory, contract.file), "utf8"),
  })));
  return { contracts, legacyTokens: catalog.legacyTokens };
}

export function renderLanguageContracts(contracts) {
  return `<!-- Generated by scripts/generate-reference-docs.mjs. Do not edit directly. -->

# Tested language examples

These examples are compiled and exercised by the language contract tests. The snippets below come directly from the tested source files.

${contracts.map((contract) => `## ${contract.title}

${contract.description}

\`\`\`funscript
${contract.source.trimEnd()}
\`\`\`
`).join("\n")}`;
}

/** Report unclassified tokens so callers can give contributors an actionable error. */
export function unclassifiedTokens(tokens, contracts, legacyTokens) {
  const classified = new Set([...legacyTokens, ...contracts.flatMap((contract) => contract.tokens)]);
  return [...new Set(tokens)].filter((token) => !classified.has(token)).sort();
}
